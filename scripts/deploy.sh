#!/usr/bin/env bash
# Deploy one exact commit to a Render service, verify it is live and smoke-test it (#25, #26, #27).
# Shared by .github/workflows/deploy-dev.yml, deploy-prod.yml and rollback.yml; no deploy logic
# lives in the workflow YAML.
#
# Usage:
#   DEPLOY_HOOK_URL=<render-deploy-hook-url> scripts/deploy.sh <env-name> <base-url> <full-sha>
#   e.g. DEPLOY_HOOK_URL="$RENDER_DEV_DEPLOY_HOOK" \
#          scripts/deploy.sh dev https://echonotes-dev.onrender.com <40-char-sha>
#
# Steps (any failure exits non-zero):
#   1. Validate the SHA (exactly 40 hex chars) and record the commit running before (best effort).
#   2. Trigger the Render deploy hook with `ref=<sha>`. 200 = deploy started. 202 = another
#      deploy is in progress: retry with backoff for up to DEPLOY_HOOK_WAIT seconds. Any other
#      status (404 = unknown SHA or bad key) = failure.
#   3. Poll <base-url>/api/health every DEPLOY_POLL_INTERVAL seconds until `commit` == sha
#      (timeout DEPLOY_TIMEOUT). 5xx, timeouts and connection errors are tolerated (free-tier
#      builds are slow and instances cold-start). If health reports an `environment`, it must
#      equal <env-name> (guards against pairing a hook with the wrong URL).
#   4. Run `SMOKE_ALLOW_EMPTY_TEXT=1 SMOKE_EXPECT_COMMIT=<sha> scripts/smoke.sh <base-url>`.
#
# Smoke against dev/prod uses the environment's REAL transcription provider (Groq) with the
# 1 s silent clip generated by smoke.sh: one real Groq call per deploy, made by the deployed
# service with its own key. This is a deliberate tech-lead decision. CI test jobs still never
# call Groq and CI never holds the Groq key; this script needs no Groq key either.
# Other SMOKE_* variables in the caller's environment reach smoke.sh unchanged: deploy-dev.yml
# sets SMOKE_SUMMARY=1 + SMOKE_SUMMARY_ALLOW_PROVIDER_ERROR=1 (one real Gemini summary per dev
# deploy, made by the service with its own key); prod and rollbacks do not.
#
# Secrets: the hook URL is read only from the DEPLOY_HOOK_URL env var. It is never printed (not
# even on curl errors, where only the HTTP status is shown), never passed on the curl command
# line (it goes through `curl --config -` on stdin), and in GitHub Actions it is also masked with
# ::add-mask::. Do not run this script with `set -x` / `bash -x`.
#
# Environment:
#   DEPLOY_HOOK_URL          (required) Render deploy hook URL (contains the secret key)
#   PREVIOUS_COMMIT          commit recorded by the caller as running before (summary only)
#   DEPLOY_SUMMARY_TITLE     heading for the job summary section (default "Deploy <env>")
#   DEPLOY_TIMEOUT=900       seconds to wait for /api/health to report the new commit
#   DEPLOY_POLL_INTERVAL=15  seconds between health polls
#   DEPLOY_HOOK_WAIT=600     seconds to keep retrying the hook while it answers 202
#   DEPLOY_HOOK_BACKOFF=15   first retry delay after a 202 (doubles, capped at 60 s)
#   DEPLOY_EXPECT_ENVIRONMENT  expected `environment` in health (default <env-name>; "" skips)
#   SMOKE_SCRIPT             smoke script to run (default scripts/smoke.sh next to this file;
#                            the tests in scripts/tests/ point it at a stub)
#   GITHUB_STEP_SUMMARY      when set (GitHub Actions), a markdown summary is appended to it
#
# Exit codes: 0 deployed + verified + smoke passed, 1 failure, 2 usage error.
#
# Tests (local mock hook + health server, no real Render calls): bash scripts/tests/test_deploy.sh
set -euo pipefail

usage() {
  echo "usage: DEPLOY_HOOK_URL=... $0 <env-name> <base-url> <full-40-char-sha>" >&2
}

if [ "$#" -ne 3 ] || [ -z "$1" ] || [ -z "$2" ] || [ -z "$3" ]; then
  usage
  exit 2
fi

ENV_NAME="$1"
BASE_URL="${2%/}"
SHA="$3"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SMOKE_SCRIPT="${SMOKE_SCRIPT:-$SCRIPT_DIR/smoke.sh}"
DEPLOY_TIMEOUT="${DEPLOY_TIMEOUT:-900}"
DEPLOY_POLL_INTERVAL="${DEPLOY_POLL_INTERVAL:-15}"
DEPLOY_HOOK_WAIT="${DEPLOY_HOOK_WAIT:-600}"
DEPLOY_HOOK_BACKOFF="${DEPLOY_HOOK_BACKOFF:-15}"
EXPECT_ENV="${DEPLOY_EXPECT_ENVIRONMENT-$ENV_NAME}"
PREVIOUS_COMMIT="${PREVIOUS_COMMIT:-}"
SUMMARY_TITLE="${DEPLOY_SUMMARY_TITLE:-Deploy $ENV_NAME}"

log() { printf '%s  %s\n' "$(date -u +%H:%M:%S)" "$*"; }
safe_url() { printf '%s' "$1" | sed -E 's#//[^/@]*@#//***@#'; }

if ! printf '%s' "$SHA" | grep -Eq '^[0-9a-f]{40}$'; then
  echo "ERROR: <full-sha> must be exactly 40 lowercase hex characters" >&2
  usage
  exit 2
fi
if [ -z "${DEPLOY_HOOK_URL:-}" ]; then
  echo "ERROR: DEPLOY_HOOK_URL is not set" >&2
  exit 2
fi
case "$DEPLOY_HOOK_URL" in
  http://* | https://*) ;;
  *)
    echo "ERROR: DEPLOY_HOOK_URL is not an http(s) URL" >&2
    exit 2
    ;;
esac
[ -f "$SMOKE_SCRIPT" ] || { echo "ERROR: smoke script not found: $SMOKE_SCRIPT" >&2; exit 2; }
command -v curl >/dev/null 2>&1 || { echo "ERROR: curl not found" >&2; exit 1; }

# Mask the hook (and its key alone) in GitHub Actions logs, in case anything ever echoes it.
if [ "${GITHUB_ACTIONS:-}" = "true" ]; then
  echo "::add-mask::$DEPLOY_HOOK_URL"
  hook_key="$(printf '%s' "$DEPLOY_HOOK_URL" | sed -nE 's#.*[?&]key=([^&]+).*#\1#p')"
  if [ -n "$hook_key" ]; then echo "::add-mask::$hook_key"; fi
  unset hook_key
fi

# A Python 3 that really runs (on Windows `python3` may be a Store stub), for JSON parsing.
PY=""
for candidate in python3 python; do
  if command -v "$candidate" >/dev/null 2>&1 &&
    "$candidate" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)' >/dev/null 2>&1; then
    PY="$candidate"
    break
  fi
done
[ -n "$PY" ] || { echo "ERROR: no working python3/python found" >&2; exit 1; }

native_path() {
  if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else printf '%s' "$1"; fi
}
WORK_DIR="$(mktemp -d "${TMPDIR:-/tmp}/echonotes-deploy.XXXXXX")"
WORK="$(native_path "$WORK_DIR")"

# ---------------------------------------------------------------------------------------------
# Summary state (written by the EXIT trap, also on failure)
# ---------------------------------------------------------------------------------------------
START_TS=$(date +%s)
RESULT="failed"
FAILED_STEP=""
BEFORE_COMMIT="unknown"
DEPLOY_ID=""
HOOK_SECS="-"
VERIFY_SECS="-"
SMOKE_SECS="-"
LIVE_ENV=""

short() { printf '%s' "${1:0:12}"; }

write_summary() {
  [ -n "${GITHUB_STEP_SUMMARY:-}" ] || return 0
  local total=$(($(date +%s) - START_TS))
  local status_line
  if [ "$RESULT" = "success" ]; then
    status_line="success"
  else
    status_line="**FAILED** at step: ${FAILED_STEP:-unknown}"
  fi
  {
    echo "### $SUMMARY_TITLE"
    echo ""
    echo "| | |"
    echo "|---|---|"
    echo "| Environment | \`$ENV_NAME\`${LIVE_ENV:+ (health reports \`$LIVE_ENV\`)} |"
    echo "| URL | $(safe_url "$BASE_URL") |"
    echo "| Target commit | \`$SHA\` |"
    echo "| Running before | \`$BEFORE_COMMIT\` |"
    if [ -n "$PREVIOUS_COMMIT" ]; then
      echo "| Previous commit (recorded by workflow) | \`$PREVIOUS_COMMIT\` |"
    fi
    echo "| Render deploy id | ${DEPLOY_ID:-n/a} |"
    echo "| Result | $status_line |"
    echo "| Durations | hook ${HOOK_SECS}s, verify ${VERIFY_SECS}s, smoke ${SMOKE_SECS}s, total ${total}s |"
    echo ""
  } >>"$GITHUB_STEP_SUMMARY"
}

on_exit() {
  local status=$?
  set +e
  if [ "$status" -eq 0 ]; then RESULT="success"; fi
  write_summary
  rm -rf "$WORK_DIR"
  if [ "$status" -eq 0 ]; then
    log "DEPLOY OK: $ENV_NAME is running $(short "$SHA") and the smoke test passed"
  else
    log "DEPLOY FAILED ($ENV_NAME, $(short "$SHA")) at step: ${FAILED_STEP:-unknown} (exit $status)"
  fi
  exit "$status"
}
trap on_exit EXIT
trap 'exit 130' INT TERM

fail() {
  FAILED_STEP="$1"
  shift
  log "ERROR: $*"
  exit 1
}

# health_read -> sets H_CODE, H_COMMIT, H_ENV (never fails; missing values are empty)
H_CODE=""
H_COMMIT=""
H_ENV=""
health_read() {
  H_CODE="$(curl -sS -o "$WORK/health.json" -w '%{http_code}' --max-time 30 \
    "$BASE_URL/api/health" 2>/dev/null)" || H_CODE="000"
  H_COMMIT=""
  H_ENV=""
  if [ "$H_CODE" = "200" ]; then
    local parsed
    parsed="$("$PY" - "$WORK/health.json" <<'PY' 2>/dev/null || true
import json, sys
try:
    with open(sys.argv[1], encoding="utf-8") as fh:
        data = json.load(fh)
except Exception:
    data = {}
if not isinstance(data, dict):
    data = {}
print(str(data.get("commit") or ""), str(data.get("environment") or ""))
PY
)"
    case "$parsed" in
      *" "*)
        H_COMMIT="${parsed%% *}"
        H_ENV="${parsed#* }"
        ;;
    esac
  fi
  return 0
}

log "deploy $ENV_NAME -> $(safe_url "$BASE_URL") commit $SHA"

# ---------------------------------------------------------------------------------------------
# 1. Record what is running before (best effort, single short read)
# ---------------------------------------------------------------------------------------------
health_read
if [ "$H_CODE" = "200" ] && [ -n "$H_COMMIT" ]; then
  BEFORE_COMMIT="$H_COMMIT"
fi
log "running before: $BEFORE_COMMIT (health HTTP $H_CODE)"
if [ -n "$PREVIOUS_COMMIT" ]; then
  log "previous commit recorded by the workflow: $PREVIOUS_COMMIT"
fi

# ---------------------------------------------------------------------------------------------
# 2. Trigger the deploy hook with ref=<sha> (retry 202 with bounded backoff)
# ---------------------------------------------------------------------------------------------
case "$DEPLOY_HOOK_URL" in
  *\?*) hook_target="${DEPLOY_HOOK_URL}&ref=${SHA}" ;;
  *) hook_target="${DEPLOY_HOOK_URL}?ref=${SHA}" ;;
esac

hook_start=$(date +%s)
hook_deadline=$((hook_start + DEPLOY_HOOK_WAIT))
backoff="$DEPLOY_HOOK_BACKOFF"
attempt=0
while :; do
  attempt=$((attempt + 1))
  # The URL is passed on stdin (curl --config -) so it never appears in argv or in error text.
  code="$(printf 'url = "%s"\n' "$hook_target" |
    curl -sS -K - --data '' -o "$WORK/hook.json" -w '%{http_code}' --max-time 60 2>/dev/null)" ||
    code="000"
  case "$code" in
    200)
      DEPLOY_ID="$("$PY" - "$WORK/hook.json" <<'PY' 2>/dev/null || true
import json, sys
try:
    with open(sys.argv[1], encoding="utf-8") as fh:
        data = json.load(fh)
    deploy = data.get("deploy") if isinstance(data, dict) else None
    value = (deploy or {}).get("id") if isinstance(deploy, dict) else data.get("id")
    print(value or "")
except Exception:
    print("")
PY
)"
      log "hook: HTTP 200, deploy started (deploy id ${DEPLOY_ID:-n/a}, attempt $attempt)"
      break
      ;;
    202)
      now=$(date +%s)
      if [ "$now" -ge "$hook_deadline" ]; then
        HOOK_SECS=$((now - hook_start))
        fail "trigger hook" "hook still answers HTTP 202 (another deploy in progress) after ${DEPLOY_HOOK_WAIT}s"
      fi
      log "hook: HTTP 202, another deploy is in progress; retrying in ${backoff}s (attempt $attempt)"
      sleep "$backoff"
      backoff=$((backoff * 2))
      if [ "$backoff" -gt 60 ]; then backoff=60; fi
      ;;
    404)
      HOOK_SECS=$(($(date +%s) - hook_start))
      fail "trigger hook" "hook: HTTP 404 (unknown commit SHA for this service, or invalid hook key)"
      ;;
    *)
      HOOK_SECS=$(($(date +%s) - hook_start))
      fail "trigger hook" "hook: HTTP $code (expected 200)"
      ;;
  esac
done
unset hook_target
HOOK_SECS=$(($(date +%s) - hook_start))

# ---------------------------------------------------------------------------------------------
# 3. Poll /api/health until it reports the target commit
# ---------------------------------------------------------------------------------------------
verify_start=$(date +%s)
verify_deadline=$((verify_start + DEPLOY_TIMEOUT))
poll=0
while :; do
  poll=$((poll + 1))
  health_read
  elapsed=$(($(date +%s) - verify_start))
  if [ "$H_CODE" = "200" ] && [ "$H_COMMIT" = "$SHA" ]; then
    LIVE_ENV="$H_ENV"
    VERIFY_SECS="$elapsed"
    log "verify: health reports $(short "$SHA") environment=${H_ENV:-?} after ${elapsed}s (poll $poll)"
    break
  fi
  log "verify: poll $poll HTTP $H_CODE commit=$(short "${H_COMMIT:-?}") (waiting for $(short "$SHA"), ${elapsed}s)"
  if [ "$(date +%s)" -ge "$verify_deadline" ]; then
    VERIFY_SECS="$elapsed"
    fail "verify commit" "health did not report $SHA within ${DEPLOY_TIMEOUT}s"
  fi
  sleep "$DEPLOY_POLL_INTERVAL"
done

if [ -n "$EXPECT_ENV" ] && [ -n "$LIVE_ENV" ] && [ "$LIVE_ENV" != "$EXPECT_ENV" ]; then
  fail "verify environment" "health reports environment '$LIVE_ENV', expected '$EXPECT_ENV'"
fi

# ---------------------------------------------------------------------------------------------
# 4. Smoke test the key journey against the live service (real provider, silent clip)
# ---------------------------------------------------------------------------------------------
smoke_start=$(date +%s)
log "smoke: running $(basename "$SMOKE_SCRIPT") against $(safe_url "$BASE_URL")"
if SMOKE_ALLOW_EMPTY_TEXT=1 SMOKE_EXPECT_COMMIT="$SHA" bash "$SMOKE_SCRIPT" "$BASE_URL"; then
  SMOKE_SECS=$(($(date +%s) - smoke_start))
else
  SMOKE_SECS=$(($(date +%s) - smoke_start))
  fail "smoke test" "smoke test failed against $(safe_url "$BASE_URL")"
fi
